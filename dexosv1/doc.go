// Package dexosv1 是 DEX-OS 开放 API v1(`/v1/*`)的 Go 客户端。
//
// 与 [github.com/chainupcloud/dex-sdk-go/dexos] 的分工:dexos 走旧接口(数字市场号 / 账户号);
// 本包走 v1 —— 市场按符号(`BTC-USD`)寻址,账户按主钱包地址 + 子账户寻址([AccountRef]),
// 线上的价量是十进制字符串。
//
// # 价量仍是整数
//
// 对外的价格是 tick(uint32)、数量是 lot(uint64),与 dexos 包和 EIP-712 结构体同一个数量空间。
// 十进制字符串只在线上出现:进出本包时按市场的 priceDecimals / sizeDecimals 精确换算([Scale]),
// 不整除就报错,**从不四舍五入** —— 一个被悄悄舍入的价格签出来就是另一张单。
//
// 不是委托价 / 成交价的派生量(开仓均价、名义额、盈亏、费用、余额)保持十进制字符串,
// 需要原子单位时用 [ParseFixed] 按 token 小数位换。
//
// # 写入
//
// 两种写入身份,各自一条 nonce 序列:
//
//   - [Session]:API 钱包代签(AgentExec)。批量下单、批量撤单、原子换单、撤全部、断线保护 —— 做市用它。
//   - [Wallet]:主钱包自签(EIP-712 具名结构体)。单笔下单 / 撤单、设杠杆、授权 API 钱包。
//
// 写入串行,一律等结论(`ack=result`,等待上限 [Client.AckWait],最多 5s):nonce 前不前进要看结论。
// 业务拒绝是终局结论,不锁会话;结论未知(202、传输失败、5xx、批量回执缺项)就锁定会话,用 Pending()
// 给出的请求身份查 [Client.Request] 核对之后再新建会话。每个请求的身份(requestId)在发出前就按签名算好,
// 与服务端同一定义;每个写回执都必须带回同一个 requestId,缺了或对不上都按结论未知处理。
//
// # 阶段
//
// 已有(跟到 v1.1):只读接口 —— 市场目录与盘口、价格与 24h 统计、K 线、账户汇总(含纪元与风险组)/
// 持仓 / 挂单、成交与资金流水、账户价值与盈亏历史(portfolio)、金库头寸、nonce、API 钱包列表与反查、
// 请求回执 —— 与上面的写入。金库身份(v1.1 §4.3)与 WS 客户端在后续阶段补上。
//
// # 限流
//
// 429 解析成 [*RateLimitedError](扣光的是 IP 桶还是账户桶、RetryAfter、那个桶的读数),
// 本包不重试、不等待 —— 怎么退让(例如只暂停一个币对)由调用方决定。
